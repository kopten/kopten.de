#!/usr/bin/env python3
"""Kontaktformular: Gemeinde-Auswahl + Empfänger-Mapping aus der XML erzeugen.

Schreibt
  * worker-api/src/gemeinden-contacts.js  — slug -> {label, to[]} (nur serverseitig,
    wird NICHT an Website-Besucher ausgeliefert)
  * die <option>-Liste in kontakt.html und en/contact.html (zwischen den Markern
    GEMEINDE-OPTIONS:START / GEMEINDE-OPTIONS:END)

Empfänger je Gemeinde: <kontakt><email>, sonst alle (eindeutigen) E-Mails aus
<ansprechpartner>. Ohne Adresse greift im Worker der Fallback auf CONTACT_TO_EMAIL.
"""

import json
import re
import xml.etree.ElementTree as ET
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
XML = ROOT / 'data' / 'kopten_gemeinden.xml'
WORKER_OUT = ROOT / 'worker-api' / 'src' / 'gemeinden-contacts.js'
PAGES = ['kontakt.html', 'en/contact.html']
EMAIL_RE = re.compile(r'^[^\s@]+@[^\s@]+\.[^\s@]+$')
START, END = '<!-- GEMEINDE-OPTIONS:START -->', '<!-- GEMEINDE-OPTIONS:END -->'


def recipients(g):
    emails = []
    k = g.find('kontakt')
    if k is not None:
        emails += [e.text for e in k.findall('email')]
    if not emails:
        ap = g.find('ansprechpartner')
        if ap is not None:
            emails += [e.text for e in ap.iter('email')]
    seen, out = set(), []
    for e in emails:
        e = (e or '').strip()
        if EMAIL_RE.match(e) and e.lower() not in seen:
            seen.add(e.lower())
            out.append(e)
    return out


def main():
    items = []
    for g in ET.parse(XML).getroot().findall('gemeinde'):
        label = (g.findtext('gemeindeort') or g.findtext('name') or g.get('id')).strip()
        items.append((g.get('id'), label, recipients(g)))
    items.sort(key=lambda i: i[1].lower())

    mapping = {slug: {'label': l, 'to': r} for slug, l, r in items}
    WORKER_OUT.write_text(
        "// AUTO-GENERATED by generate_contact_gemeinden.py — DO NOT EDIT MANUALLY\n"
        "// Source: data/kopten_gemeinden.xml\n\n"
        f"export const GEMEINDEN = {json.dumps(mapping, indent=2, ensure_ascii=False)};\n",
        encoding='utf-8')

    options = '\n'.join(
        f'                  <option value="{escape(s)}">{escape(l)}</option>' for s, l, _ in items)
    for rel in PAGES:
        p = ROOT / rel
        html = p.read_text(encoding='utf-8')
        pat = re.compile(re.escape(START) + r'.*?' + re.escape(END), re.S)
        if not pat.search(html):
            print(f"  ! Marker fehlt in {rel}")
            continue
        p.write_text(pat.sub(lambda _: f'{START}\n{options}\n                  {END}', html), encoding='utf-8')
    print(f"{len(items)} Gemeinden, {sum(1 for m in mapping.values() if m['to'])} mit eigener E-Mail")


if __name__ == '__main__':
    main()
